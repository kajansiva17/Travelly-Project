import {test,expect} from '@playwright/test'

test('capture polished Home page desktop and mobile states',async({page},testInfo)=>{
 for(const [name,width,height] of [['desktop',1440,900],['mobile',390,844]]){
  await page.setViewportSize({width,height})
  await page.goto('/')
  await page.evaluate(()=>document.fonts.ready)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  await page.screenshot({path:testInfo.outputPath(`home-after-${name}.png`),fullPage:true})
 }
 for(const width of [1920,1440,1366,390,375]){
  await page.setViewportSize({width,height:900})
  await page.goto('/')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  expect(await page.locator('.search-panel').isVisible()).toBe(true)
  expect(await page.locator('.benefit-card').count()).toBe(4)
 }
})

test('Home page glass surfaces keep the navy, cyan and coral visual system',async({page})=>{
 await page.setViewportSize({width:1440,height:900})
 await page.goto('/')
 const visuals=await page.evaluate(()=>{
  const style=selector=>getComputedStyle(document.querySelector(selector))
  const header=style('.site-header .header-inner')
  const login=style('.navigation .login-link')
  const cta=style('.navigation .nav-cta')
  const panel=style('.search-panel')
  const tab=style('.search-tabs button.selected')
  const field=style('.search-input')
  const service=style('.service-card')
  const trust=style('.benefit-card')
  return{header:{background:header.backgroundImage,border:header.borderTopColor,blur:header.backdropFilter},login:{background:login.backgroundImage,border:login.borderTopColor},cta:cta.backgroundImage,panel:{background:panel.backgroundImage,border:panel.borderTopColor,blur:panel.backdropFilter},tab:tab.backgroundImage,field:{background:field.backgroundImage,border:field.borderTopColor},service:{background:service.backgroundImage,border:service.borderTopColor,blur:service.backdropFilter},trust:{background:trust.backgroundImage,border:trust.borderTopColor,blur:trust.backdropFilter}}
 })
 expect(visuals.header.blur).toContain('blur')
 expect(visuals.login.border).not.toBe('rgba(0, 0, 0, 0)')
 expect(visuals.cta).toContain('rgb(211, 44, 80)')
 expect(visuals.panel.blur).toContain('blur')
 expect(visuals.tab).toContain('rgb(211, 44, 80)')
 expect(visuals.field.border).not.toBe('rgba(0, 0, 0, 0)')
 expect(visuals.service.blur).toContain('blur')
 expect(visuals.trust.blur).toContain('blur')
 await page.getByLabel('Pickup location').focus()
 await expect(page.locator('.search-input').first()).toHaveCSS('outline-style','solid')
 await page.emulateMedia({reducedMotion:'reduce'})
 expect(await page.locator('.service-card').first().evaluate(element=>getComputedStyle(element).transitionDuration)).toBe('1e-05s')
 expect(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior)).toBe('auto')
})

test('Home navbar and search controls preserve their existing destinations and behavior',async({page})=>{
 await page.setViewportSize({width:1440,height:900})
 await page.route('**/api/v1/**',route=>route.fulfill({status:503,json:{detail:'Unavailable in visual test'}}))
 await page.goto('/')
 const nav=page.getByRole('navigation',{name:'Main navigation'})
 await nav.getByRole('link',{name:'Vehicles',exact:true}).click()
 await expect(page).toHaveURL(/#rides$/)
 await nav.getByRole('link',{name:'Home',exact:true}).click()
 await expect(page).toHaveURL(/\/$/)
 await nav.getByRole('link',{name:'Log in',exact:true}).click()
 await expect(page).toHaveURL(/\/login$/)
 await page.goto('/')
 await nav.getByRole('link',{name:'Find a ride',exact:true}).click()
 await expect(page).toHaveURL(/#search$/)
 const hire=page.getByRole('tab',{name:'Hire a vehicle'})
 const tickets=page.getByRole('tab',{name:'Book tickets'})
 const rentals=page.getByRole('tab',{name:'Rentals'})
 await tickets.click()
 await expect(tickets).toHaveAttribute('aria-selected','true')
 await rentals.click()
 await expect(rentals).toHaveAttribute('aria-selected','true')
 await hire.click()
 await expect(hire).toHaveAttribute('aria-selected','true')
 await page.getByLabel('Pickup location').fill('Colombo')
 await page.getByLabel('Destination').fill('Kandy')
 await page.getByLabel('Travel date').fill('2030-01-02T10:00')
 await page.getByLabel('Passengers').selectOption('3–6 passengers')
 await page.getByRole('button',{name:'Find a ride',exact:true}).last().click()
 await expect(page).toHaveURL(/\/hire$/)
})

test('mobile Home navigation remains accessible and links to Login',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await expect(page.getByRole('button',{name:'Open navigation'})).toBeVisible()
 await page.getByRole('button',{name:'Open navigation'}).click()
 const nav=page.getByRole('navigation',{name:'Main navigation'})
 await expect(nav.getByRole('link',{name:'Log in',exact:true})).toBeVisible()
 await nav.getByRole('link',{name:'Log in',exact:true}).click()
 await expect(page).toHaveURL(/\/login$/)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
